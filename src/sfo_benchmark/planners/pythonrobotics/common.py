"""Shared implementation for PythonRobotics grid-planner adapters."""

from __future__ import annotations

from abc import abstractmethod
from contextlib import redirect_stdout
from io import StringIO
import time
from typing import Any

import numpy as np

from sfo_benchmark.core.environment import Environment
from sfo_benchmark.core.path import Path
from sfo_benchmark.core.result import PlanningResult
from sfo_benchmark.planners.base import BasePlanner

from .grid_conversion import environment_to_grid_problem


class PythonRoboticsGridAdapter(BasePlanner):
    upstream_algorithm: str
    upstream_file: str

    @abstractmethod
    def _planner_class(self) -> type[Any]:
        ...

    def plan(
        self,
        environment: Environment,
        *,
        seed: int,
        run_id: int,
    ) -> PlanningResult:
        resolution = float(self.config.parameters.get("resolution", 1.0))
        grid = environment_to_grid_problem(environment, resolution=resolution)
        planner_class = self._planner_class()

        started_at = time.perf_counter()
        upstream_log = StringIO()

        try:
            with redirect_stdout(upstream_log):
                planner = planner_class(
                    grid.obstacle_x,
                    grid.obstacle_y,
                    grid.resolution,
                    grid.robot_radius,
                )
                rx, ry = planner.planning(
                    float(environment.start[0]),
                    float(environment.start[1]),
                    float(environment.goal[0]),
                    float(environment.goal[1]),
                )

            elapsed = time.perf_counter() - started_at

            if not rx or not ry or len(rx) != len(ry):
                return PlanningResult(
                    algorithm=self.name,
                    map_id=environment.map_id,
                    run_id=run_id,
                    seed=seed,
                    success=False,
                    execution_time=elapsed,
                    message="PythonRobotics returned no complete path.",
                    metadata=self._metadata(resolution, upstream_log.getvalue()),
                )

            points = np.column_stack((rx[::-1], ry[::-1])).astype(float)
            points[0] = environment.start
            points[-1] = environment.goal
            points = self._remove_consecutive_duplicates(points)

            return PlanningResult(
                algorithm=self.name,
                map_id=environment.map_id,
                run_id=run_id,
                seed=seed,
                success=True,
                execution_time=elapsed,
                path=Path(points),
                message="Path generated by unmodified vendored PythonRobotics code.",
                metadata=self._metadata(resolution, upstream_log.getvalue()),
            )

        except (KeyError, ValueError, IndexError, RuntimeError) as error:
            elapsed = time.perf_counter() - started_at
            return PlanningResult(
                algorithm=self.name,
                map_id=environment.map_id,
                run_id=run_id,
                seed=seed,
                success=False,
                execution_time=elapsed,
                message=f"PythonRobotics planner failed: {error}",
                metadata=self._metadata(resolution, upstream_log.getvalue()),
            )

    @staticmethod
    def _remove_consecutive_duplicates(points: np.ndarray) -> np.ndarray:
        if len(points) < 2:
            return points
        keep = np.ones(len(points), dtype=bool)
        keep[1:] = np.any(np.diff(points, axis=0) != 0.0, axis=1)
        return points[keep]

    def _metadata(self, resolution: float, log: str) -> dict[str, Any]:
        return {
            "family": "PythonRobotics",
            "upstream_algorithm": self.upstream_algorithm,
            "upstream_file": self.upstream_file,
            "upstream_repository": "AtsushiSakai/PythonRobotics",
            "adapter_resolution": resolution,
            "upstream_stdout": log.strip(),
            "source_modified": False,
        }
