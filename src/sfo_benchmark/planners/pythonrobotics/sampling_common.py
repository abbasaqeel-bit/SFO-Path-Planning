"""Shared adapter logic for PythonRobotics sampling planners."""

from __future__ import annotations

from abc import abstractmethod
from contextlib import redirect_stderr, redirect_stdout
from io import StringIO
import random
import time
from typing import Any

import numpy as np

from sfo_benchmark.core.collision import CollisionChecker
from sfo_benchmark.core.environment import Environment
from sfo_benchmark.core.path import Path
from sfo_benchmark.core.result import PlanningResult
from sfo_benchmark.planners.base import BasePlanner

from .sampling_conversion import environment_to_sampling_problem


class PythonRoboticsSamplingAdapter(BasePlanner):
    """Base class that preserves native sampling-planner behavior."""

    upstream_algorithm: str
    upstream_file: str

    @abstractmethod
    def _run_upstream(
        self,
        *,
        environment: Environment,
        seed: int,
        sampling_problem: Any,
    ) -> tuple[list[list[float]] | None, dict[str, Any]]:
        raise NotImplementedError

    def plan(
        self,
        environment: Environment,
        *,
        seed: int,
        run_id: int,
    ) -> PlanningResult:
        random.seed(seed)
        np.random.seed(seed)

        rectangle_resolution = float(
            self.config.parameters.get(
                "rectangle_resolution",
                1.0,
            )
        )
        sampling_problem = environment_to_sampling_problem(
            environment,
            rectangle_resolution=rectangle_resolution,
        )

        upstream_log = StringIO()
        started = time.perf_counter()

        try:
            with redirect_stdout(upstream_log), redirect_stderr(
                upstream_log
            ):
                raw_path, state = self._run_upstream(
                    environment=environment,
                    seed=seed,
                    sampling_problem=sampling_problem,
                )

            elapsed = time.perf_counter() - started

            if not raw_path:
                partial_path = self._diagnostic_path(
                    state.get("partial_path"),
                    environment,
                )
                return PlanningResult(
                    algorithm=self.name,
                    map_id=environment.map_id,
                    run_id=run_id,
                    seed=seed,
                    success=False,
                    execution_time=elapsed,
                    path=partial_path,
                    message=(
                        "PythonRobotics returned no complete path; the "
                        "closest native tree branch is retained only for "
                        "diagnostic plotting."
                        if partial_path is not None
                        else "PythonRobotics returned no complete path."
                    ),
                    metadata=self._metadata(
                        rectangle_resolution,
                        upstream_log.getvalue(),
                        state,
                    ),
                )

            points = np.asarray(raw_path, dtype=float)
            if points.ndim != 2 or points.shape[1] != 2:
                raise ValueError(
                    f"Unexpected path shape: {points.shape}"
                )

            # PythonRobotics sampling planners return Goal -> Start.
            if np.linalg.norm(points[0] - environment.goal) < np.linalg.norm(
                points[-1] - environment.goal
            ):
                points = points[::-1]

            points[0] = environment.start
            points[-1] = environment.goal
            points = self._remove_duplicates(points)
            path = Path(points)
            collision_free = CollisionChecker(
                environment
            ).path_is_free(path)

            return PlanningResult(
                algorithm=self.name,
                map_id=environment.map_id,
                run_id=run_id,
                seed=seed,
                success=collision_free,
                execution_time=elapsed,
                path=path,
                iterations=self._optional_int(
                    state.get("iterations")
                ),
                message=(
                    "Collision-free path generated by vendored "
                    "PythonRobotics code."
                    if collision_free
                    else (
                        "PythonRobotics returned a path, but common "
                        "validation detected a collision."
                    )
                ),
                metadata=self._metadata(
                    rectangle_resolution,
                    upstream_log.getvalue(),
                    state,
                ),
            )

        except (
            KeyError,
            ValueError,
            IndexError,
            RuntimeError,
            ZeroDivisionError,
        ) as error:
            elapsed = time.perf_counter() - started
            return PlanningResult(
                algorithm=self.name,
                map_id=environment.map_id,
                run_id=run_id,
                seed=seed,
                success=False,
                execution_time=elapsed,
                message=f"PythonRobotics planner failed: {error}",
                metadata=self._metadata(
                    rectangle_resolution,
                    upstream_log.getvalue(),
                    {"error_type": type(error).__name__},
                ),
            )

    @staticmethod
    def _remove_duplicates(points: np.ndarray) -> np.ndarray:
        if len(points) < 2:
            return points
        keep = np.ones(len(points), dtype=bool)
        keep[1:] = np.any(np.diff(points, axis=0) != 0.0, axis=1)
        return points[keep]

    @classmethod
    def _diagnostic_path(
        cls,
        raw_path: Any,
        environment: Environment,
    ) -> Path | None:
        if raw_path is None:
            return None
        points = np.asarray(raw_path, dtype=float)
        if points.ndim != 2 or points.shape[1] != 2 or len(points) < 2:
            return None
        if np.linalg.norm(points[-1] - environment.start) < np.linalg.norm(
            points[0] - environment.start
        ):
            points = points[::-1]
        points[0] = environment.start
        points = cls._remove_duplicates(points)
        return Path(points) if len(points) >= 2 else None

    @staticmethod
    def _optional_int(value: Any) -> int | None:
        return None if value is None else int(value)

    def _metadata(
        self,
        rectangle_resolution: float,
        log: str,
        state: dict[str, Any],
    ) -> dict[str, Any]:
        return {
            "family": "sampling_based",
            "upstream_algorithm": self.upstream_algorithm,
            "upstream_file": self.upstream_file,
            "upstream_repository": "AtsushiSakai/PythonRobotics",
            "source_modified": False,
            "rectangle_conversion": (
                "conservative_circle_lattice"
            ),
            "rectangle_resolution": rectangle_resolution,
            "upstream_stdout": log.strip(),
            **state,
        }
